SELECT SUM(u.a - 2), COUNT(DISTINCT u.a) FROM u;
SELECT 'K8 0.6666666666666666 3: VAR_SAMP(a - 2), COUNT(DISTINCT a), without a key' AS q;
SELECT VAR_SAMP(u.a - 2), COUNT(DISTINCT u.a) FROM u;
SELECT 'K9 8 3: SUM(a), COUNT(DISTINCT a), without a key' AS q;
SELECT SUM(u.a), COUNT(DISTINCT u.a) FROM u;
SELECT 'K10 16 3: SUM(a * 2), COUNT(DISTINCT a), without a key' AS q;
