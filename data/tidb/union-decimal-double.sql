-- Observation (round 15): the type of a UNION column whose arms are a DECIMAL and a DOUBLE.
-- MySQL derives DOUBLE (the DOUBLE arm keeps its digits).  What TiDB does is printed here.
-- expected (MySQL 8.4 / 9): 0.7853981633974483 in both lines of U1, and 1.5 / 0.7853981633974483 in U2
DROP DATABASE IF EXISTS vs_ud; CREATE DATABASE vs_ud; USE vs_ud;
CREATE TABLE t (i INT, d DECIMAL(10,2));
INSERT INTO t VALUES (1, 1.50);
SELECT 'U1 DOUBLE UNION ALL AVG(int)' AS q;
SELECT ATAN(t.i) AS k FROM t UNION ALL SELECT AVG(t.i) FROM t;
SELECT 'U2 DECIMAL UNION ALL DOUBLE' AS q;
SELECT t.d AS k FROM t UNION ALL SELECT ATAN(t.i) FROM t;
SELECT 'U3 DOUBLE UNION ALL MAX(int)' AS q;
SELECT ATAN(t.i) AS k FROM t UNION ALL SELECT MAX(t.i) FROM t;
SELECT 'U4 DOUBLE UNION ALL a DECIMAL literal' AS q;
SELECT ATAN(t.i) AS k FROM t UNION ALL SELECT 1.5;
SELECT 'U5 the type of U2 (CREATE TABLE AS)' AS q;
CREATE TABLE u AS SELECT t.d AS k FROM t UNION ALL SELECT ATAN(t.i) FROM t;
SHOW CREATE TABLE u;
DROP DATABASE vs_ud;
